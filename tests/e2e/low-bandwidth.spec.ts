import { test, expect } from "@playwright/test";
import { validGuestFixture } from "../../packages/testing/src";
test("360x800 constrained CPU/network, offline exploration, safe private writes and reconnect", async ({ page, context }, info) => {
 test.setTimeout(150000);
 await page.setViewportSize({ width: 360, height: 800 });
 const cdp = await context.newCDPSession(page);
 await cdp.send("Network.enable");
 await cdp.send("Emulation.setCPUThrottlingRate", { rate: 4 });
 await cdp.send("Network.emulateNetworkConditions", { offline: false, latency: 180, downloadThroughput: 500000, uploadThroughput: 125000, connectionType: "cellular4g" });
 let bytes = 0; cdp.on("Network.loadingFinished", (e) => { bytes += e.encodedDataLength; });
 expect((await context.request.post("http://localhost:3001/api/guest", { headers: { Origin: "http://localhost:3001" }, data: validGuestFixture })).ok()).toBe(true);
 const start = Date.now();
 await page.goto("http://localhost:3001/play");
 await expect(page.getByTestId("campus-world")).toHaveAttribute("data-ready", "true", { timeout: 90000 });
 const boot = Date.now() - start;
 await page.evaluate(() => navigator.serviceWorker.ready);
 await page.reload();
 await expect(page.getByTestId("campus-world")).toHaveAttribute("data-ready", "true", { timeout: 60000 });
 await context.setOffline(true);
 await page.getByRole("button", { name: "Open virtual phone" }).click();
 await page.getByRole("button", { name: "Campus map", exact: true }).click();
 await expect(page.getByRole("img", { name: "Virtual campus map" })).toBeVisible();
 const denied = await page.evaluate(async () => { try { await fetch("/api/account/world", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{}" }); return false; } catch { return true; } });
 expect(denied).toBe(true);
 const cached = await page.evaluate(async () => { const results: string[] = []; for (const key of await caches.keys()) for (const req of await (await caches.open(key)).keys()) results.push(new URL(req.url).pathname); return results; });
 expect(cached.some((p) => /^\/api\/(account|guest|feedback|guide)/.test(p))).toBe(false);
 expect(cached.some((p) => p.endsWith("/latest") || p.endsWith("/information"))).toBe(false);
 await page.keyboard.press("Escape");
 await expect(page.getByTestId("campus-world")).toHaveAttribute("data-ready", "true");
 await page.reload();
 await expect(page.getByRole("heading", { name: "The network has stepped out." })).toBeVisible();
 await context.setOffline(false);
 await page.goto("http://localhost:3001/play");
 await expect(page.getByTestId("campus-world")).toHaveAttribute("data-ready", "true", { timeout: 60000 });
 // A bounded 15-second CI soak samples real diagnostics. Longer physical sessions remain a human gate.
 await page.waitForTimeout(15000);
 const diagnostics = await page.getByTestId("campus-world").evaluate((el) => ({ frameMs: el.getAttribute("data-average-frame-ms"), heapWarning: el.getAttribute("data-memory-warning"), failures: el.getAttribute("data-asset-failures") }));
 await info.attach("constrained-network-measurement", { body: JSON.stringify({ viewport: "360x800", cpuSlowdown: 4, latencyMs: 180, downloadBytesPerSecond: 500000, bootMs: boot, transferredBytes: bytes, diagnostics, note: "Chromium emulation, not a physical device benchmark" }), contentType: "application/json" });
});
test("manifest failure offers retry and optional art failure keeps world usable", async ({ page, context }) => {
 test.setTimeout(90000);
 await context.request.post("http://localhost:3001/api/guest", { headers: { Origin: "http://localhost:3001" }, data: validGuestFixture });
 await page.route("**/api/world/futa/latest", (r) => r.fulfill({ status: 503, contentType: "application/json", body: "{}" }));
 await page.goto("http://localhost:3001/play");
 await expect(page.getByText("Campus gates are temporarily closed. Please retry.")).toBeVisible();
 await page.unroute("**/api/world/futa/latest");
 await page.route("**/world-assets/**", (r) => r.abort());
 await page.getByRole("button", { name: "Retry" }).click();
 await expect(page.getByTestId("campus-world")).toHaveAttribute("data-ready", "true", { timeout: 30000 });
 await page.getByRole("button", { name: "Open virtual phone" }).click();
 await expect(page.getByRole("dialog", { name: "CW Pocket virtual phone" })).toBeVisible();
});
